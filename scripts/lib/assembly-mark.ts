/**
 * HOW WAS THIS ARTEFACT ASSEMBLED? (Annie, 2026-08-21 — R516.)
 *
 * **A generated artefact's claims about the store can be wrong and CAN BE CHECKED — there is a query
 * behind them to re-run. A hand-assembled one's cannot be checked at all.**
 *
 * `narrator-redraft-proposal-0413f8ee` claimed `ENG-002-pp-23 key: "…"` and it was a distractor.
 * **Nothing could re-derive that claim, because no query produced it** — it was written by hand, and
 * a hand-written claim about a row is somebody's account of the store rather than the store.
 *
 * **Meeting a claim about a key in a hand-assembled document should tell her she is reading an
 * account.** That is the whole purpose of the field: not provenance for the record, but a warning at
 * the moment of reading.
 *
 * **UNFORGEABLE BY ABSENCE.** An artefact with no `assembly` field is HAND-ASSEMBLED by default —
 * because the alternative is that the field means nothing on exactly the artefacts it exists for.
 * A hand-written document is precisely the one nobody remembers to mark.
 */

export type Assembly =
  /** Every claim came from a query. Wrong claims are re-derivable and therefore checkable. */
  | 'GENERATED_FROM_ROWS'
  /** Written or edited by a person. Claims about the store are an account, not a read. */
  | 'ASSEMBLED_BY_HAND'
  /** Generated, then hand-edited. Treated as HAND for reading purposes — the edit is unverifiable. */
  | 'GENERATED_THEN_EDITED';

export interface AssemblyMark {
  assembly: Assembly;
  /** What a reader should do differently. Printed on the artefact, not just stored. */
  readAs: string;
  /** For generated artefacts: the script that produced it, so a claim can be re-derived. */
  generatedBy: string | null;
}

const READ_AS: Record<Assembly, string> = {
  GENERATED_FROM_ROWS:
    'Every claim here about an item, an option or a key came from a query and can be re-derived. '
    + 'If one is wrong, re-running the generator finds it.',
  ASSEMBLED_BY_HAND:
    'THIS IS SOMEBODY\'S ACCOUNT OF THE STORE, NOT THE STORE. A claim here about a key, an option or '
    + 'a carrier was written by a person and NOTHING can re-derive it. Check any such claim against '
    + 'the row before ruling on it.',
  GENERATED_THEN_EDITED:
    'Generated and then edited by hand. The edits are not re-derivable, so treat any claim about a '
    + 'key, an option or a carrier as an account rather than a read.',
};

export function assemblyMark(assembly: Assembly, generatedBy: string | null = null): AssemblyMark {
  return { assembly, readAs: READ_AS[assembly], generatedBy };
}

/**
 * **ABSENCE IS HAND-ASSEMBLED.** Never `undefined`, never a guess — the default is the unsafe reading
 * because the safe one would let an unmarked hand-written file pass as generated.
 */
export function assemblyOf(artefact: unknown): AssemblyMark {
  const a = (artefact as { assembly?: unknown; stamp?: { assembly?: unknown } } | null) ?? {};
  const raw = (a.assembly ?? a.stamp?.assembly) as { assembly?: Assembly } | Assembly | undefined;
  const kind = typeof raw === 'string' ? raw : raw?.assembly;
  if (kind === 'GENERATED_FROM_ROWS' || kind === 'GENERATED_THEN_EDITED') {
    return assemblyMark(kind, (raw as { generatedBy?: string })?.generatedBy ?? null);
  }
  return assemblyMark('ASSEMBLED_BY_HAND');
}

/** The line an artefact prints where she reads it — never only in a stamp block. */
export function assemblyBanner(mark: AssemblyMark): string {
  const label = mark.assembly === 'GENERATED_FROM_ROWS' ? 'GENERATED FROM ROWS'
    : mark.assembly === 'GENERATED_THEN_EDITED' ? 'GENERATED, THEN EDITED BY HAND'
      : 'ASSEMBLED BY HAND';
  return `**HOW THIS WAS ASSEMBLED: ${label}.** ${mark.readAs}`
    + (mark.generatedBy ? ` Generated by \`${mark.generatedBy}\`.` : '');
}
